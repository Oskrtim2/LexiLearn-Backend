import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { TtsVoicePersona } from '@prisma/client';
import { Transform, Type } from 'class-transformer';
import {
  IsEnum,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateIf,
  ValidateNested,
} from 'class-validator';

export class VoiceSettingsDto {
  @ApiPropertyOptional({
    enum: TtsVoicePersona,
    description: 'Overrides the persona stored in the student profile.',
  })
  @IsOptional()
  @IsEnum(TtsVoicePersona)
  persona?: TtsVoicePersona;

  @ApiPropertyOptional({
    example: 'Joanna',
    description: 'Provider-specific voice identifier. Leave empty to use the persona voice.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  @Matches(/^[A-Za-z0-9._-]+$/, { message: 'voiceId has an invalid format' })
  voiceId?: string;

  @ApiPropertyOptional({ example: 1, minimum: 0.75, maximum: 1.25 })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0.75)
  @Max(1.25)
  speed?: number;

  @ApiPropertyOptional({ example: 1, minimum: 0.75, maximum: 1.5 })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0.75)
  @Max(1.5)
  pitch?: number;
}

export class SynthesizeSpeechDto {
  @ApiPropertyOptional({
    example: 'Cada palabra es un pequeño paso.',
    minLength: 1,
    maxLength: 5000,
    description: 'Raw text. Provide exactly one of text or textChunkId.',
  })
  @ValidateIf((dto: SynthesizeSpeechDto) => dto.textChunkId === undefined)
  @Transform(({ value }: { value: unknown }) =>
    typeof value === 'string' ? value.normalize('NFC').replace(/\s+/g, ' ').trim() : value,
  )
  @IsString()
  @MinLength(1)
  @MaxLength(5000)
  text?: string;

  @ApiPropertyOptional({
    format: 'uuid',
    description:
      'Owned sentence chunk ID from an OCR result. Provide exactly one of text or textChunkId.',
  })
  @ValidateIf((dto: SynthesizeSpeechDto) => dto.text === undefined)
  @IsUUID('4')
  textChunkId?: string;

  @ApiPropertyOptional({ type: VoiceSettingsDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => VoiceSettingsDto)
  voice?: VoiceSettingsDto;
}

export class SynthesizeSpeechResponseDto {
  @ApiProperty({ format: 'uuid' })
  assetId!: string;

  @ApiPropertyOptional({ format: 'uuid', nullable: true })
  textChunkId!: string | null;

  @ApiProperty({ example: 'Cada palabra es un pequeño paso.' })
  text!: string;

  @ApiProperty({ example: 'aws-polly' })
  provider!: string;

  @ApiProperty({ example: 'Joanna' })
  voiceId!: string;

  @ApiProperty({ example: 1 })
  speed!: number;

  @ApiProperty({ example: 1 })
  pitch!: number;

  @ApiProperty({ example: 'audio/mpeg' })
  mimeType!: string;

  @ApiProperty({
    example: 'http://localhost:3000/api/v1/tts/audio/8d1c...?token=eyJhbGciOi...',
    description: 'Short-lived signed URL for the cached MP3 buffer.',
  })
  signedUrl!: string;

  @ApiProperty({ format: 'date-time' })
  expiresAt!: string;

  @ApiProperty({
    example: true,
    description: 'True when the audio was served from the content-hash cache.',
  })
  cached!: boolean;

  @ApiProperty({ example: 34 })
  characterCount!: number;

  @ApiPropertyOptional({ example: 2300, nullable: true })
  durationMs!: number | null;
}

export class SignedAudioQueryDto {
  @ApiProperty({ description: 'Short-lived JWT generated by POST /tts/synthesize.' })
  @IsString()
  @MinLength(20)
  @MaxLength(4096)
  token!: string;
}
